using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using Deployify.Core.Models;
using Deployify.Core.SecretBackends;

namespace Deployify.Target.Kubernetes;

/// <summary>
/// Turns one service's Kubernetes manifests into a Helm chart: the same objects kubectl would
/// apply, with the image, replica count, resources and ingress host lifted into values.yaml so
/// they can be overridden with <c>--set</c>. Each service is a chart of its own, installed as a
/// release named after the service in the service's namespace.
/// </summary>
/// <remarks>
/// The Namespace is not in the chart: Helm keeps its release record in the release namespace,
/// so that namespace has to exist before the chart is installed. Deployify's Helm target creates
/// it (with Deployify's labels); by hand, install with <c>--create-namespace</c>.
/// </remarks>
public sealed partial class HelmChartWriter
{
    /// <summary>Folder under the output directory that holds one chart per service.</summary>
    public const string ChartsFolder = "helm";

    /// <summary>Default chart version when targetConfig.helm.chartVersion isn't set.</summary>
    public const string DefaultChartVersion = "0.1.0";

    /// <summary>Directory of a service's chart.</summary>
    public static string ChartDirectory(string outputDirectory, string service)
        => Path.Combine(outputDirectory, ChartsFolder, service);

    /// <summary>
    /// Writes the chart of <paramref name="svc"/> to <c>{outputDirectory}/helm/{service}</c> and
    /// returns the paths written. templates/ is rewritten from scratch each time, so a resource
    /// the service no longer has (a Secret, an Ingress) never lingers in the chart.
    /// </summary>
    public async Task<List<string>> WriteChartAsync(
        KubernetesServiceManifest svc, string outputDirectory, string? chartVersion = null, CancellationToken ct = default)
    {
        var chartDir = ChartDirectory(outputDirectory, svc.ServiceName);
        var templatesDir = Path.Combine(chartDir, "templates");
        if (Directory.Exists(templatesDir))
        {
            Directory.Delete(templatesDir, recursive: true);
        }

        Directory.CreateDirectory(templatesDir);

        var image = SplitImage(ImageReference.Format(svc.Image!, svc.ImageTag));
        var files = new List<string>
        {
            await KubernetesManifestGenerator.WriteAsync(chartDir, "Chart.yaml",
                RenderChartYaml(svc, chartVersion ?? DefaultChartVersion, image.Tag), ct),
            await KubernetesManifestGenerator.WriteAsync(chartDir, "values.yaml", RenderValues(svc, image), ct)
        };

        var policyPath = Path.Combine(chartDir, "vault-policy.hcl");
        File.Delete(policyPath);
        foreach (var (name, content) in KubernetesManifestGenerator.Render(svc))
        {
            switch (name)
            {
                case "namespace.yaml":
                    continue; // see remarks
                case "vault-policy.hcl":
                    // Not a manifest: kept next to the chart for reference; Helm doesn't render it.
                    files.Add(await KubernetesManifestGenerator.WriteAsync(chartDir, name, content, ct));
                    continue;
            }

            var path = await KubernetesManifestGenerator.WriteAsync(templatesDir, name, Templatize(svc, name, content), ct);
            if (name == KubernetesManifestGenerator.SecretFileName)
            {
                KubernetesManifestGenerator.RestrictToOwner(path);
            }

            files.Add(path);
        }

        // As for plain manifests: an external backend means no secret value in the chart.
        if (svc.SecretBackend != SecretBackendType.Inline && svc.HasSecret)
        {
            SecretLeakScanner.EnsureClean(files, svc.SecretData);
        }

        return files;
    }

    // ── Chart.yaml / values.yaml ─────────────────────────────────────────────

    private static string RenderChartYaml(KubernetesServiceManifest svc, string version, string tag) => $"""
apiVersion: v2
name: {svc.ServiceName}
description: {Q($"{svc.ServiceName}, generated by Deployify from the Aspire manifest")}
type: application
version: {Q(version)}
appVersion: {Q(string.IsNullOrEmpty(tag) ? "latest" : tag)}
annotations:
  deployify/service: {Q(svc.ServiceName)}
  deployify/namespace: {Q(svc.Namespace)}

""";

    private static string RenderValues(KubernetesServiceManifest svc, (string Repository, string Tag) image)
    {
        var sb = new StringBuilder();
        sb.Append($"""
# Generated by Deployify for '{svc.ServiceName}'. Regenerated on every plan; override values with
# --set or -f instead of editing this file. Install into namespace {svc.Namespace}.
replicaCount: {svc.Replicas}

image:
  repository: {Q(image.Repository)}
  # Empty when the reference is pinned by digest (repository then carries it).
  tag: {Q(image.Tag)}

resources:
  requests:
    cpu: {Q(svc.CpuRequest)}
    memory: {Q(svc.MemoryRequest)}
  limits:
    cpu: {Q(svc.CpuLimit)}
    memory: {Q(svc.MemoryLimit)}

""");
        if (svc.HasIngress)
        {
            sb.Append($"""

ingress:
  className: {Q(svc.IngressClassName)}
  host: {Q(svc.IngressHost)}

""");
        }

        return sb.ToString();
    }

    /// <summary>
    /// Splits <c>registry/name:tag</c> at the tag. A digest reference (<c>name@sha256:…</c>) is
    /// kept whole with an empty tag, as is an image with no tag at all.
    /// </summary>
    internal static (string Repository, string Tag) SplitImage(string image)
    {
        if (image.Contains('@'))
        {
            return (image, "");
        }

        var slash = image.LastIndexOf('/');
        var colon = image.LastIndexOf(':');
        return colon > slash ? (image[..colon], image[(colon + 1)..]) : (image, "");
    }

    // ── Templates ─────────────────────────────────────────────────────────────

    /// <summary>Image reference from values: <c>repository:tag</c>, or the repository alone when tag is empty.</summary>
    private const string ImageExpression =
        "{{ if .Values.image.tag }}{{ printf \"%s:%s\" .Values.image.repository (toString .Values.image.tag) }}" +
        "{{ else }}{{ .Values.image.repository }}{{ end }}";

    /// <summary>
    /// Escapes what Helm would read as template actions (the Vault agent's own template is full
    /// of <c>{{ }}</c>), then swaps the overridable fields for references to values.yaml. Each
    /// swap must hit exactly one line, so a change to the renderers can't silently leave a
    /// value hard-coded.
    /// </summary>
    internal static string Templatize(KubernetesServiceManifest svc, string fileName, string content)
    {
        var text = EscapeTemplateActions(content.ReplaceLineEndings("\n"));
        switch (fileName)
        {
            case "deployment.yaml":
                text = ReplaceOnce(text, fileName, $"\n  replicas: {svc.Replicas}\n",
                    "\n  replicas: {{ .Values.replicaCount }}\n");
                text = ReplaceOnce(text, fileName,
                    $"\n          image: {KubernetesManifestGenerator.QuoteYaml(ImageReference.Format(svc.Image!, svc.ImageTag))}\n",
                    $"\n          image: \"{ImageExpression}\"\n");
                text = ReplaceOnce(text, fileName, $"""

          resources:
            requests:
              cpu: {svc.CpuRequest}
              memory: {svc.MemoryRequest}
            limits:
              cpu: {svc.CpuLimit}
              memory: {svc.MemoryLimit}

""".ReplaceLineEndings("\n"), """

          resources:
            {{- toYaml .Values.resources | nindent 12 }}

""".ReplaceLineEndings("\n"));
                break;

            case "ingress.yaml":
                text = ReplaceOnce(text, fileName, $"\n  ingressClassName: {svc.IngressClassName}\n",
                    "\n  ingressClassName: {{ .Values.ingress.className | quote }}\n");
                text = ReplaceOnce(text, fileName, $"\n    - host: {svc.IngressHost}\n",
                    "\n    - host: {{ .Values.ingress.host | quote }}\n");
                break;
        }

        return text;
    }

    /// <summary>
    /// Makes literal <c>{{</c> and <c>}}</c> print as themselves under Helm. One pass, so the
    /// braces the escapes add aren't escaped again.
    /// </summary>
    internal static string EscapeTemplateActions(string text)
        => TemplateDelimiters().Replace(text, m => m.Value == "{{" ? "{{ \"{{\" }}" : "{{ \"}}\" }}");

    private static string ReplaceOnce(string text, string fileName, string find, string replacement)
    {
        var at = text.IndexOf(find, StringComparison.Ordinal);
        if (at < 0 || text.IndexOf(find, at + find.Length, StringComparison.Ordinal) >= 0)
        {
            throw new InvalidOperationException(
                $"Could not turn {fileName} into a Helm template: expected exactly one '{find.Trim()}'.");
        }

        return string.Concat(text.AsSpan(0, at), replacement, text.AsSpan(at + find.Length));
    }

    private static string Q(string? value) => KubernetesManifestGenerator.QuoteYaml(value);

    [GeneratedRegex(@"\{\{|\}\}")]
    private static partial Regex TemplateDelimiters();
}
