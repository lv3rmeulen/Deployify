using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;
using Deployify.Core.Expressions;

namespace Deployify.Core.SecretBackends.Vault;

/// <summary>
/// Renders values as a consul-template (Vault Agent) template. Literal text becomes Go string
/// literals and each secret parameter becomes an <c>index .Data.data "key"</c> lookup, so the
/// template itself never contains a secret. Vault Agent on Kubernetes and Nomad's
/// <c>template</c> block both understand this syntax.
/// </summary>
public static class VaultTemplate
{
    /// <summary>
    /// A JSON configuration file for .NET's <c>AddJsonFile</c>, one entry per variable.
    /// Environment variable names are converted to configuration keys
    /// (<c>ConnectionStrings__db</c> → <c>ConnectionStrings:db</c>).
    /// </summary>
    public static string JsonConfigFile(string kvApiPath, IReadOnlyDictionary<string, ResolvedValue> values)
    {
        ArgumentException.ThrowIfNullOrEmpty(kvApiPath);
        var sb = new StringBuilder();
        sb.Append("{{- with secret ").Append(GoString(kvApiPath)).Append(" -}}\n{\n");
        var entries = values.OrderBy(kv => kv.Key, StringComparer.Ordinal).ToList();
        for (var i = 0; i < entries.Count; i++)
        {
            var (key, value) = entries[i];
            sb.Append("  ").Append(JsonSerializer.Serialize(ConfigurationKey(key))).Append(": ")
              .Append("{{ ").Append(Expression(value)).Append(" | toJSON }}")
              .Append(i < entries.Count - 1 ? ",\n" : "\n");
        }

        sb.Append("}\n{{- end }}\n");
        return sb.ToString();
    }

    /// <summary>
    /// A Go template pipeline that produces the value: <c>print "Host=pg;Password=" (index .Data.data "pg-password")</c>.
    /// Must be used inside a <c>with secret</c> block.
    /// </summary>
    public static string Expression(ResolvedValue value)
    {
        var operands = new List<string>();
        var literal = new StringBuilder();

        void FlushLiteral()
        {
            if (literal.Length > 0)
            {
                operands.Add(GoString(literal.ToString()));
                literal.Clear();
            }
        }

        foreach (var part in value.Parts)
        {
            switch (part)
            {
                case ParameterPart { IsSecret: true } p:
                    FlushLiteral();
                    operands.Add($"(index .Data.data {GoString(SecretKeys.Id(p))})");
                    break;
                case ParameterPart p:
                    literal.Append(p.Value);
                    break;
                case TextPart t:
                    literal.Append(t.Text);
                    break;
                case UnresolvedPart u:
                    literal.Append(u.Placeholder);
                    break;
            }
        }

        FlushLiteral();
        // print joins string operands without separators.
        return operands.Count == 0 ? "\"\"" : $"print {string.Join(' ', operands)}";
    }

    /// <summary>Converts an environment variable name to a .NET configuration key.</summary>
    public static string ConfigurationKey(string environmentVariable)
        => environmentVariable.Replace("__", ":", StringComparison.Ordinal);

    /// <summary>
    /// A Go interpreted string literal. A JSON string is one: same quoting, and Go accepts the
    /// <c>\uXXXX</c> escapes System.Text.Json writes for &lt;, &gt;, &amp; and quotes.
    /// </summary>
    internal static string GoString(string s) => JsonSerializer.Serialize(s);
}

/// <summary>A read-only Vault policy for one service's secrets.</summary>
public static class VaultPolicy
{
    public static string ReadOnly(string kvApiPath) => $$"""
        # Generated by Deployify. Lets one service read its own secrets and nothing else.
        path "{{kvApiPath}}" {
          capabilities = ["read"]
        }

        """;
}
